await page.goto(url);
await page.waitForSelector('body[data-ready="1"]');
const shot = async (n) => page.screenshot({ path: `${out}/${n}.png` });
const tap = async (k, wait) => {
  await page.keyboard.press(k);
  await page.waitForTimeout(wait);
};
