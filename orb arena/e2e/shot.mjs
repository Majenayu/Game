// Takes screenshots of the arena and the Hero page from the running dev server.
import { chromium } from '@playwright/test';
const url = process.argv[2] ?? 'http://localhost:5173/';
const out = process.argv[3] ?? 'D:/shots';
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const gid = (s, d, c, r) => ((s * 30 + d) * 12 + c) * 8 + r;
const equip = { hat: gid(0, 5, 3, 6), gloves: gid(1, 0, 11, 5), armor: gid(2, 3, 0, 6), pants: gid(3, 0, 7, 4), shoes: gid(4, 2, 7, 4), bag: gid(5, 0, 6, 3), sword: gid(6, 12, 1, 7) };
const cr = (fam, sp, rank, level, uid) => ({ uid, id: (fam * 12 + sp) * 8 + rank, level, cards: [] });
const save = { profile: { cls: 'warrior', created: 1, onboarded: true }, nick: 'Tester', gear: { owned: Object.values(equip), equip }, creatures: { list: [cr(2, 0, 6, 45, 'a'), cr(0, 0, 3, 12, 'b'), cr(1, 1, 4, 30, 'c'), cr(5, 0, 5, 50, 'd'), cr(4, 1, 2, 1, 'e'), cr(7, 1, 7, 40, 'f')], active: 'a' } };
await page.addInitScript((s) => localStorage.setItem('orb.save3', s), JSON.stringify(save));
await page.goto(url);
await page.waitForTimeout(1500);
const quick = page.locator('[data-oquick], #oquick, button:has-text("Quick")').first();
if (await quick.isVisible().catch(() => false)) await quick.click();
await page.screenshot({ path: `${out}/start.png` });
await page.mouse.click(640, 360);
await page.locator('[data-lconfirm]').click({ timeout: 4000 }).catch(() => {});
await page.waitForTimeout(5500);
await page.screenshot({ path: `${out}/arena0.png` });
await page.locator('#leave').click();
await page.waitForSelector('#menu', { state: 'visible', timeout: 15000 });
await page.screenshot({ path: `${out}/menu.png` });
await page.locator('[data-page="loadout"]').click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/hero.png` });
await page.locator('[data-pgtab="gear"]').click().catch(() => {});
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/gear.png` });
await page.locator('#pageclose').click();
await page.locator('[data-page="campaign"]').click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/campaign1.png` });
await page.locator('.worldbox').nth(4).scrollIntoViewIfNeeded();
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/campaign5.png` });
await page.locator('#pageclose').click();
await page.locator('[data-page="summons"]').click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/summons.png` });
await page.locator('#pageclose').click();
await page.locator('#practice').click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/lobby.png` });
await page.locator('[data-lconfirm]').click().catch(() => {});
await page.waitForTimeout(5000);
await page.screenshot({ path: `${out}/arena.png` });
console.log('errors', JSON.stringify(errors));
await b.close();
